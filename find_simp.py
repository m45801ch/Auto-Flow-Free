import re

def check_dict(filepath):
    js = open(filepath).read()
    i = js.find('"zh-TW"')
    j = js.find('"zh-CN"')
    zhTW = js[i:j]
    for m in re.finditer(r'(\w+):\s*"([^"]*)"', zhTW):
        k, v = m.group(1), m.group(2)
        if any(c in SIMP for c in v):
            chars = [c for c in v if c in SIMP]
            print(f"zhTW SIMPLIFIED [{k}]: {v}  <- chars: {''.join(set(chars))}")

def check_html(filepath):
    html = open(filepath).read()
    # static text lines with CJK (not in data-i18n attrs)
    for m in re.finditer(r'>([^<>]*[\u4e00-\u9fff][^<>]*)<', html):
        txt = m.group(1).strip()
        if not txt: continue
        if any(c in SIMP for c in txt):
            chars = ''.join(set(c for c in txt if c in SIMP))
            print(f"HTML SIMPLIFIED: {txt[:80]}  <- chars: {chars}")
    # placeholders & titles
    for m in re.finditer(r'(?:placeholder|title)="([^"]*[\u4e00-\u9fff][^"]*)"', html):
        txt = m.group(1)
        if any(c in SIMP for c in txt):
            chars = ''.join(set(c for c in txt if c in SIMP))
            print(f"ATTR SIMPLIFIED: {txt[:80]}  <- chars: {chars}")

check_dict("popup.js")
check_html("popup.html")
